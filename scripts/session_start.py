"""SessionStart hook: put the board rules, the board's item counts and the startup steps into context.

Reads the hook's JSON from stdin (cwd, source) and prints a SessionStart hookSpecificOutput JSON. Silent in a
project without a board: one is used only when `.claude/claude-board.json` exists or the board file does.
Also keeps the project's copy of the rules (`rules_copy`, default notes/board_rules.md) current, for sessions
without the plugin. With `--rules-copy` it only writes that copy (for /board-init) and prints what it did.
Standard library only, so it runs wherever Python 3.8+ does.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path
from typing import Any

SETTINGS_PATH: str = ".claude/claude-board.json"
DEFAULT_BOARD: str = "claude_board.md"
DEFAULT_CRON: str = "7 * * * *"
DEFAULT_RULES_COPY: str = "notes/board_rules.md"
PLUGIN_ROOT: Path = Path(__file__).resolve().parent.parent
RULES_PATH: Path = PLUGIN_ROOT / "skills" / "board" / "board_rules.md"
WATCHER_SKELETON: Path = PLUGIN_ROOT / "templates" / "board_watcher.py"
# A copied watcher whose FILL IN parts aren't written yet still has this line.
UNFILLED: re.Pattern[str] = re.compile(r"^SKELETON_UNFILLED\b.*=\s*True", re.MULTILINE)
# Board sections in order, with the key letter of their items.
SECTIONS: dict[str, str] = {"Todo": "T", "Asks": "A", "Recommends": "R", "Queue": "Q"}
SINGULAR: dict[str, str] = {"Todo": "todo", "Asks": "ask", "Recommends": "recommend", "Queue": "queued"}
# First words of a generated rules copy; a copy without them is hand-written and left alone.
GENERATED_MARK: str = "Generated by the claude-board plugin"
# A Todo Claude has taken up: "- T2 (Running: Q5c): ..."
TAGGED_TODO: re.Pattern[str] = re.compile(r"-\s*T\d+[a-z]?\s*\([^)]*\):")
# Stands for the project's absolute path in the rules copy, which is tracked in git and shared across machines.
REPO_PLACEHOLDER: str = "<repo>"


def derive_helper_name(repo: str) -> str:
    """Return the helper's default name for a repo: "Haiku" + 3 letters of its first word + 3 of its second.

    Words split at "-", "_", ".", spaces and case changes, so PolymarketHunter, polymarket-hunter and
    polymarket_hunter all give HaikuPolHun. A single word gives 6 letters (scraper -> HaikuScrape), a word under
    3 letters is used whole (ai-bot -> HaikuAiBot), words after the second are dropped. Unique per repo, and
    "Haiku" first keeps the helpers together in ListAgents.
    """
    # Apostrophes join, not split: Waeve's_Burgers is Waeves + Burgers, not Waeve + s
    words: list[str] = re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|\d+", re.sub(r"['’]", "", repo))
    if not words:
        return "HaikuHelper"
    if len(words) == 1:
        return "Haiku" + words[0][:6].capitalize()
    return "Haiku" + words[0][:3].capitalize() + words[1][:3].capitalize()


def repo_name(project: Path) -> str:
    """Return the repo's folder name; for a Claude Code worktree (<repo>/.claude/worktrees/<name>), the repo's."""
    if project.parent.name == "worktrees" and project.parent.parent.name == ".claude":
        return project.parent.parent.parent.name
    return project.name


def load_settings(project: Path) -> dict[str, Any] | None:
    """Return the project's board settings, {} when only the default board exists, None without a board.

    A `helper` of "auto" comes back as the derived name (`derive_helper_name`).

    Raises:
        ValueError: the settings file isn't a JSON object.
    """
    path: Path = project / SETTINGS_PATH
    if path.is_file():
        settings: Any = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(settings, dict):
            raise ValueError(f"{SETTINGS_PATH} must hold a JSON object")
        if settings.get("helper") == "auto":
            settings["helper"] = derive_helper_name(repo_name(project))
        return settings
    if (project / DEFAULT_BOARD).is_file():
        return {}
    return None


def todo_items(board_text: str) -> dict[str, str]:
    """Return the Todo section's items by key ("T3"), from lines at column 0 that start with a dash or a number.

    Loose on purpose, like a project watcher's untagged-Todo alert: the user writes Todos quickly ("3 pull
    bookies", "- check the log"), so those count too. A numbered item is keyed "T<n>", an unnumbered one by its
    text; indented sub-points don't count.
    """
    items: dict[str, str] = {}
    section: str = ""
    line: str
    for line in board_text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip().lower()
        elif section == "todo" and re.match(r"[-\d]", line):
            number: re.Match[str] | None = re.match(r"-?\s*T?(\d+)\b", line.strip(), re.IGNORECASE)
            items[f"T{number.group(1)}" if number else line.strip()] = line.strip()
    return items


def untagged_todos(board_text: str) -> list[str]:
    """Return the keys of Todos Claude hasn't taken up yet (no status tag after the key), loose ones included."""
    return [key for key, line in todo_items(board_text).items() if not TAGGED_TODO.match(line)]


def count_items(board_text: str) -> dict[str, int]:
    """Count each section's top-level items: Todos loosely (`todo_items`), the rest as "- A2...", "- Q1..." lines."""
    counts: dict[str, int] = {name: 0 for name in SECTIONS}
    counts["Todo"] = len(todo_items(board_text))
    section: str | None = None
    line: str
    for line in board_text.splitlines():
        heading: re.Match[str] | None = re.match(r"^##\s+(\w+)", line)
        if heading:
            section = heading.group(1) if heading.group(1) in SECTIONS else None
        elif section and section != "Todo" and re.match(rf"^- {SECTIONS[section]}\d+", line):
            counts[section] += 1
    return counts


def summary_line(board_name: str, counts: dict[str, int], untagged: list[str] | None = None) -> str:
    """Return e.g. "Read claude_board.md: 2 todos (untagged: T3), 0 asks, 10 recommends, 11 queued"."""
    parts: list[str] = []
    name: str
    for name, n in counts.items():
        word: str = SINGULAR[name]
        part: str = f"{n} {word}" if n == 1 or word == "queued" else f"{n} {word}s"
        if name == "Todo" and untagged:
            part += f" (untagged: {', '.join(untagged)})"
        parts.append(part)
    return f"Read {board_name}: " + ", ".join(parts)


def status_job_message(project: str, board: str, status: str | None, cron: str) -> str:
    """Return the message that hands the hourly status job to the helper session (paths as shown to it)."""
    shown: str = f"prints {board}"
    if status is not None:
        shown += f", then {status},"
    return (
        f"Repo location: {project}\n"
        "Hourly status job, requested by the user (if your permission check blocks CronCreate, ask your user to "
        "approve it).\n"
        f'The job: cron "{cron}", prompt exactly "status update"; each run {shown} each verbatim inside its own '
        "plain code fence (three backticks, no language) so the app shows the raw text instead of rendering "
        "markdown, with no thinking, summary or comment.\n"
        "Run CronList; if no such job exists, create it with CronCreate and run the status update once right "
        "away. Reply in one line whether the job existed or was created."
    )


def helper_howto(helper: str, board_name: str) -> str:
    """Return the instructions for starting the helper session, for a user who has none running."""
    return (
        "To start one: open this project folder in a new Claude Code session (the Claude Desktop app's Code tab, "
        f"or `claude` in a terminal), switch to a small model (`/model haiku`) and name it `/rename {helper}` so "
        f"ListAgents finds it; approve its first CronCreate. It reads and writes {board_name} like any session in "
        "the folder; with Remote Control on (`/remote-control`, or Settings > Claude Code > Connect new sessions "
        "to Remote Control) its hourly prints can be followed from claude.ai/code or the Claude phone app."
    )


def shown_path(project: str, relative: str) -> str:
    """Return a project file's path as shown: under REPO_PLACEHOLDER with "/", else the real absolute path."""
    return f"{project}/{relative}" if project == REPO_PLACEHOLDER else str(Path(project) / relative)


def watcher_state(project: Path, settings: dict[str, Any]) -> str:
    """Return "" without a `watcher` setting, else "missing", "unfilled" (still the skeleton) or "ready"."""
    name: Any = settings.get("watcher")
    if not name:
        return ""
    path: Path = project / str(name)
    if not path.is_file():
        return "missing"
    return "unfilled" if UNFILLED.search(path.read_text(encoding="utf-8", errors="replace")) else "ready"


def wait_alert_command(settings: dict[str, Any]) -> str | None:
    """Return the wait-alert command: the `wait_alert` setting, else the `watcher` script's --wait-alert, else None."""
    if settings.get("wait_alert"):
        return str(settings["wait_alert"])
    return f"python -u {settings['watcher']} --wait-alert" if settings.get("watcher") else None


def startup_steps(settings: dict[str, Any], source: str, project: str, board_exists: bool,
                  board_line: str, watcher: str = "") -> list[str]:
    """Return the numbered startup steps for a session start.

    Args:
        settings: The project's board settings.
        source: The session start's source (startup, clear, resume, compact); a compaction skips the helper.
        project: The project's path as shown (absolute in the hook, REPO_PLACEHOLDER in the rules copy).
        board_exists: Whether the board file exists.
        board_line: The example board summary line to tell the user.
        watcher: The watcher's state (`watcher_state`); "missing" or "unfilled" adds a step to set it up.
    """
    board_name: str = str(settings.get("board", DEFAULT_BOARD))
    board: str = shown_path(project, board_name)
    status_name: str | None = settings.get("status_file")
    status: str | None = shown_path(project, status_name) if status_name else None
    helper: str | None = settings.get("helper")
    wait_alert: str | None = wait_alert_command(settings)
    steps: list[str] = []
    if board_exists:
        steps.append(
            f"Read the board ({board}) and these rules"
            + (f", then the status file ({status})" if status is not None else "")
            + f'; then tell the user, e.g. "{board_line}", naming any untagged Todo.'
        )
    else:
        template: str = str(settings.get("template", PLUGIN_ROOT / "templates" / "claude_board.example.md"))
        steps.append(f"The board {board} doesn't exist: create it from the template ({template}).")
    if helper and source != "compact":
        message: str = status_job_message(project, board, status, str(settings.get("helper_cron", DEFAULT_CRON)))
        steps.append(
            f"Helper session: {helper}. After ListAgents, if it is live, send it this message (SendMessage); if "
            f"not, gently ask the user to start one. {helper_howto(helper, Path(board_name).name)}\n{message}"
        )
    if watcher in ("missing", "unfilled"):
        shown: str = shown_path(project, str(settings["watcher"]))
        steps.append(
            (f"The settings name a watcher ({shown}) that doesn't exist yet: copy the plugin's skeleton "
             f"({WATCHER_SKELETON}) there. Then it" if watcher == "missing" else
             f"The watcher ({shown}) is still the plugin's skeleton (SKELETON_UNFILLED = True), so it")
            + " needs filling in for this project before Claude relies on it: write its FILL IN parts (JOBS: the "
            "long runs to watch; project_checks: anything else that should alert), posting an Ask for anything "
            "that needs the user; set SKELETON_UNFILLED = False; try it with --once; then start it detached with "
            "--supervise (commands in its docstring)."
        )
    if wait_alert and watcher != "missing":
        steps.append(
            f"Start the wait-alert as a background task: {wait_alert} (run from the project root). It replaces "
            "only this session's older wait (or one whose session ended); if it reports that another live session "
            "holds the alerts, leave them there and don't restart it. Otherwise start it again after handling "
            "each alert."
        )
    return steps


def rules_copy_path(project: Path, settings: dict[str, Any]) -> Path | None:
    """Return where the project keeps its copy of the rules, None when the settings turn it off ("" or null)."""
    name: Any = settings.get("rules_copy", DEFAULT_RULES_COPY)
    return project / str(name) if name else None


def render_rules_copy(settings: dict[str, Any]) -> str:
    """Return the project's rules copy: the plugin's rules, then this project's startup steps filled in.

    Paths in it are under REPO_PLACEHOLDER, so the copy is the same on every machine.
    """
    rules: str = RULES_PATH.read_text(encoding="utf-8")
    title: str
    body: str
    title, _, body = rules.partition("\n")
    board_name: str = Path(str(settings.get("board", DEFAULT_BOARD))).name
    steps: list[str] = startup_steps(settings, "startup", REPO_PLACEHOLDER, True,
                                     f"Read {board_name}: 1 todo, 2 asks, ...")
    lines: list[str] = [
        title,
        "",
        f"{GENERATED_MARK} from its rules and this project's {SETTINGS_PATH}, for sessions without the plugin. "
        "The plugin rewrites it at session start: change the plugin or the settings, not this file.",
        body.rstrip("\n"),
        "",
        "## This project's startup, filled in",
        "",
        f"{REPO_PLACEHOLDER} is this repo's absolute path; give the helper absolute paths.",
        "",
    ]
    i: int
    step: str
    for i, step in enumerate(steps, 1):
        lines.append(f"{i}. " + step.replace("\n", "\n   "))
    return "\n".join(lines) + "\n"


def sync_rules_copy(project: Path, settings: dict[str, Any]) -> str | None:
    """Write the rules copy if it's missing or a generated copy that has gone stale.

    Returns:
        A note for the context ("Wrote ...", or that a hand-written copy was left alone); None when nothing
        changed or the copy is turned off.
    """
    path: Path | None = rules_copy_path(project, settings)
    if path is None:
        return None
    text: str = render_rules_copy(settings)
    if path.is_file():
        old: str = path.read_text(encoding="utf-8")
        if old.replace("\r\n", "\n") == text:  # git may check it out with CRLF on Windows
            return None
        if GENERATED_MARK not in old:
            return (f"{path} is hand-written (no \"{GENERATED_MARK}\" line), so the plugin left it alone; the "
                    "plugin's rules below are the ones that apply.")
    path.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n": the same bytes on every machine, so the copy doesn't flip line endings in git
    with open(path, "w", encoding="utf-8", newline="\n") as copy:
        copy.write(text)
    return f"Wrote the rules copy {path} from the plugin's rules (commit it with the next work)."


def build_context(project: Path, settings: dict[str, Any], source: str) -> str:
    """Return the additionalContext text for a session start of the given source (startup, clear, resume, compact)."""
    board: Path = project / str(settings.get("board", DEFAULT_BOARD))
    rules: str = RULES_PATH.read_text(encoding="utf-8")
    lines: list[str] = [
        f"claude-board plugin (session start: {source}). The board rules follow; they apply to this project.",
        "",
    ]
    board_line: str = ""
    if board.is_file():
        text: str = board.read_text(encoding="utf-8")
        board_line = summary_line(board.name, count_items(text), untagged_todos(text)) + " (counted by the hook)"
    steps: list[str] = startup_steps(settings, source, str(project), board.is_file(), board_line,
                                     watcher_state(project, settings))
    lines.append("Startup steps now:")
    i: int
    step: str
    for i, step in enumerate(steps, 1):
        lines.append(f"{i}. {step}")
    note: str | None = sync_rules_copy(project, settings)
    if note:
        lines += ["", note]
    lines += ["", rules]
    return "\n".join(lines)


def main() -> int:
    """Run the hook; returns the exit code (0 also on a bad settings file, reported in context instead)."""
    if "--rules-copy" in sys.argv[1:]:
        here: Path = Path.cwd()
        found: dict[str, Any] = load_settings(here) or {}
        print(sync_rules_copy(here, found) or "The rules copy is current (or turned off by rules_copy).")
        return 0
    raw: str = sys.stdin.read() if not sys.stdin.isatty() else ""
    event: dict[str, Any] = json.loads(raw) if raw.strip() else {}
    project: Path = Path(os.environ.get("CLAUDE_PROJECT_DIR") or event.get("cwd") or os.getcwd())
    source: str = str(event.get("source", "startup"))
    try:
        settings: dict[str, Any] | None = load_settings(project)
        if settings is None:
            return 0
        context: str = build_context(project, settings, source)
    except (OSError, ValueError) as error:
        context = f"claude-board plugin: couldn't read the board settings ({error}); fix {SETTINGS_PATH}."
    output: dict[str, Any] = {
        "hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": context}
    }
    # ASCII-only JSON, so a Windows console code page can't garble it.
    sys.stdout.write(json.dumps(output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
